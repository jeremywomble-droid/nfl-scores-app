#!/usr/bin/env python3
"""Regenerate the predictions feed (data/predictions.json) from the web app.

The web app (Muse artifact, slug "nfl-scores") is the single source of truth
for predictions: its `getscores` action returns the current week's games with
the analyst model's LOCKED picks (game_picks store). This script converts one
week's getscores payload into the app's predictions JSON format.

Since v1.2.2 the app fetches its picks AT RUNTIME from the committed feed
file data/predictions.json in this (public) repo — the web artifact itself
is NOT publicly reachable over HTTP (fullstack artifact, not shared), so
this file is the bridge. Weekly procedure — NO build needed:

    1. Invoke the artifact action `getscores` (optionally with {"week": N})
       and save the JSON result to a file, e.g. /tmp/getscores.json
    2. python3 scripts/sync_predictions.py /tmp/getscores.json data/predictions.json
    3. Commit data/predictions.json and push. The app picks the new week up
       on its next open / widget refresh.

Omitting the output path writes app/src/main/assets/predictions.json instead
— the bundled offline-fallback snapshot, refreshed whenever a release is
built anyway.
"""
import json
import math
import sys
from datetime import datetime, timezone
from pathlib import Path

src = Path(sys.argv[1])
data = json.loads(src.read_text())
week = data["week"]
games = data["games"]

preds = []
for g in games:
    p = g.get("prediction")
    if not p:
        raise SystemExit(f"game {g['away']['abbr']} @ {g['home']['abbr']} has no prediction — refusing to sync a partial week")
    pick = p["pickAbbr"]
    pct = p["awayWinPct"] if p["pick"] == "away" else p["homeWinPct"]
    preds.append({
        "week": week,
        "away": g["away"]["abbr"],
        "home": g["home"]["abbr"],
        "predAway": p["projectedAway"],
        "predHome": p["projectedHome"],
        "pick": pick,
        "confidence": int(math.floor(pct + 0.5)),
    })

out = {
    "week": week,
    "seasonYear": data.get("seasonYear"),
    "source": "nfl-scores web app (getscores action) — analyst model locked picks; regenerated by scripts/sync_predictions.py",
    "syncedAt": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    "predictions": preds,
}
repo_root = Path(__file__).resolve().parent.parent
if len(sys.argv) > 2:
    dest = Path(sys.argv[2])
    if not dest.is_absolute():
        dest = repo_root / dest
else:
    dest = repo_root / "app/src/main/assets/predictions.json"
dest.write_text(json.dumps(out, indent=1) + "\n")
print(f"wrote {dest} — week {week}, {len(preds)} predictions")
